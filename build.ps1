# Builds build\dbghelp.dll (the plugin) and build\harness.exe (its self-test).
# Needs MSYS2's UCRT64 GCC + binutils (gcc -m32 compiles 32-bit objects; no
# 32-bit C runtime is needed because the plugin links only to Windows DLLs).
param(
    [string]$Toolchain = "C:\msys64\ucrt64\bin"
)
$ErrorActionPreference = "Stop"
$root = $PSScriptRoot
$src = Join-Path $root "src"
$out = Join-Path $root "build"
New-Item -ItemType Directory -Force $out | Out-Null
if (-not (Test-Path (Join-Path $Toolchain "gcc.exe"))) { throw "gcc not found in $Toolchain (install MSYS2 with mingw-w64-ucrt-x86_64-gcc)" }
$env:PATH = "$Toolchain;$env:PATH"

function Invoke-Tool([string]$exe, [string[]]$arguments) {
    $ErrorActionPreference = "Continue"  # tools print warnings on stderr; the exit code decides
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "$exe failed (exit $LASTEXITCODE)" }
}

# Named exports of a PE file.
function Get-PeExportNames([string]$Path) {
    $b = [IO.File]::ReadAllBytes($Path)
    $pe = [BitConverter]::ToInt32($b, 0x3C)
    $nsec = [BitConverter]::ToUInt16($b, $pe + 6)
    $optsz = [BitConverter]::ToUInt16($b, $pe + 20)
    $opt = $pe + 24
    $ddir = if ([BitConverter]::ToUInt16($b, $opt) -eq 0x20b) { $opt + 112 } else { $opt + 96 }
    $secs = for ($i = 0; $i -lt $nsec; $i++) {
        $s = $opt + $optsz + 40 * $i
        $vsize = [BitConverter]::ToUInt32($b, $s + 8)
        if ($vsize -eq 0) { $vsize = [BitConverter]::ToUInt32($b, $s + 16) }
        [pscustomobject]@{ VA = [BitConverter]::ToUInt32($b, $s + 12); Size = $vsize; Raw = [BitConverter]::ToUInt32($b, $s + 20) }
    }
    $off = { param($rva) foreach ($s in $secs) { if ($rva -ge $s.VA -and $rva -lt $s.VA + $s.Size) { return $rva - $s.VA + $s.Raw } }; throw "bad RVA $rva" }
    $e = & $off ([BitConverter]::ToUInt32($b, $ddir))
    $count = [BitConverter]::ToUInt32($b, $e + 24)
    $names = & $off ([BitConverter]::ToUInt32($b, $e + 32))
    for ($i = 0; $i -lt $count; $i++) {
        $p = & $off ([BitConverter]::ToUInt32($b, $names + 4 * $i))
        $end = $p; while ($b[$end] -ne 0) { $end++ }
        [Text.Encoding]::ASCII.GetString($b, $p, $end - $p)
    }
}

# 1. dbghelp proxy: one stub per export of the 32-bit system dbghelp.dll
$sysDbghelp = Join-Path $env:WINDIR "SysWOW64\dbghelp.dll"
$all = @(Get-PeExportNames $sysDbghelp)
$names = @($all | Where-Object { $_ -cmatch '^[A-Za-z_][A-Za-z0-9_]*$' })  # -cmatch: -match is culture-sensitive (Turkish I)
if ($names.Count -ne $all.Count) { throw "unexpected dbghelp export names: $(@($all | Where-Object { $names -notcontains $_ }) -join ', ')" }
$def = @("LIBRARY dbghelp.dll", "EXPORTS")
$asm = @("    .text")
$hdr = @("/* generated by build.ps1 from $sysDbghelp */", "#define PROXY_COUNT $($names.Count)", "static const char *const g_proxy_names[PROXY_COUNT] = {")
for ($i = 0; $i -lt $names.Count; $i++) {
    $def += "    $($names[$i])=proxy_$i"
    $hdr += "    `"$($names[$i])`","
    $asm += @(
        "    .globl _proxy_$i",
        "_proxy_${i}:",
        "    movl _g_proxy_fn+$(4 * $i), %eax",
        "    testl %eax, %eax",
        "    jz 1f",
        "    jmp *%eax",
        "1:  pushl `$$i",
        "    call _proxy_resolve",
        "    addl `$4, %esp",
        "    jmp *%eax"
    )
}
$hdr += "};"
Set-Content -Encoding ascii (Join-Path $out "dbghelp.def") $def
Set-Content -Encoding ascii (Join-Path $out "proxy_stubs.S") $asm
Set-Content -Encoding ascii (Join-Path $out "proxy_names.h") $hdr
Write-Host "Proxy: $($names.Count) dbghelp exports"

# 2. import libraries for the few Windows functions we call
#    (dlltool names its temp files after the output path, so run it from the build folder)
Push-Location $out
try {
    foreach ($lib in "kernel32", "user32") {
        Invoke-Tool dlltool @("-m", "i386", "--as-flags=--32", "-k", "-t", "tmp_$lib", "-d", (Join-Path $src "imports\$lib.def"), "-l", "lib$lib.a")
    }
} finally { Pop-Location }

# 3. compile and link
$cflags = @("-m32", "-march=i686", "-msse2", "-mfpmath=sse", "-O2", "-Wall", "-Wextra",
            "-ffreestanding", "-fno-stack-protector", "-fno-asynchronous-unwind-tables",
            "-fno-tree-loop-distribute-patterns", "-mno-stack-arg-probe", "-I", $out)
Invoke-Tool gcc ($cflags + @("-c", (Join-Path $src "ftl_speed.c"), "-o", (Join-Path $out "ftl_speed.o")))
Invoke-Tool gcc @("-m32", "-c", (Join-Path $out "proxy_stubs.S"), "-o", (Join-Path $out "proxy_stubs.o"))
Invoke-Tool ld @("-m", "i386pe", "--dll", "-e", "_DllMain@12", "--subsystem", "windows",
                 "--dynamicbase", "--nxcompat", "--enable-reloc-section", "--image-base", "0x6A000000", "-s",
                 "-o", (Join-Path $out "dbghelp.dll"),
                 (Join-Path $out "ftl_speed.o"), (Join-Path $out "proxy_stubs.o"), (Join-Path $out "dbghelp.def"),
                 "-L", $out, "-lkernel32", "-luser32")

Invoke-Tool gcc ($cflags + @("-c", (Join-Path $root "test\harness.c"), "-o", (Join-Path $out "harness.o")))
Invoke-Tool ld @("-m", "i386pe", "--subsystem", "console", "-e", "_harness_main", "-s",
                 "-o", (Join-Path $out "harness.exe"), (Join-Path $out "harness.o"),
                 "-L", $out, "-lkernel32", "-luser32")
Write-Host "Built $(Join-Path $out 'dbghelp.dll')"
